// Generates the CSS files that derive from TypeScript sources:
//
// - packages/ui/src/lib/styles/tokens.css from packages/ui/src/lib/tokens/values.ts;
// - packages/ui/src/lib/styles/schemes.css with every base scheme;
// - packages/ui-themes/src/lib/presets.css with every preset.
//
// The sources load through Vite's module runner, which resolves the extensionless
// imports of @material/material-color-utilities. With --check nothing is written, and the
// script exits with status 1 when a file on disk differs from the generated one.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createServer, createServerModuleRunner } from 'vite';

const root = fileURLToPath(new URL('../../', import.meta.url));
const cssHeader = readFileSync(`${root}tools/templates/header.css.txt`, 'utf8').trimEnd();

const server = await createServer({
	root,
	configFile: false,
	logLevel: 'error',
	appType: 'custom',
	server: { middlewareMode: true, hmr: false, ws: false },
	resolve: {
		alias: [
			{
				find: /^@oito2\/ui\/theme$/,
				replacement: `${root}packages/ui/src/lib/theme/index.ts`
			}
		]
	},
	ssr: { noExternal: ['@material/material-color-utilities', '@catppuccin/palette'] }
});
const runner = createServerModuleRunner(server.environments.ssr);

type Values = typeof import('../../packages/ui/src/lib/tokens/values.ts');
type Theme = typeof import('../../packages/ui/src/lib/theme/index.ts');
type Presets = typeof import('../../packages/ui-themes/src/lib/presets.ts');

const values: Values = await runner.import(`${root}packages/ui/src/lib/tokens/values.ts`);
const theme: Theme = await runner.import(`${root}packages/ui/src/lib/theme/index.ts`);
const presets: Presets = await runner.import(`${root}packages/ui-themes/src/lib/presets.ts`);

// Converts camelCase to kebab-case.
function kebab(name: string): string {
	return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

// Formats a family name for CSS, quoting names with spaces.
function family(name: string): string {
	return name.includes(' ') ? `'${name}'` : name;
}

// Wraps rules in the file header, a generated-file note and the oito2 layer.
function file(source: string, rules: string[]): string {
	return [
		cssHeader,
		'',
		`/* Generated by tools/generate-css from ${source}. Do not edit. */`,
		'',
		'@layer oito2 {',
		rules.join('\n\n'),
		'}',
		''
	].join('\n');
}

function tokensCss(): string {
	const { accentColors, radius, sizes, spacing, typography } = values;
	const lines: string[] = [];
	const add = (name: string, value: string | number) =>
		lines.push(`\t\t--oito2-${name}: ${value};`);
	for (const [name, value] of Object.entries(radius)) add(`radius-${kebab(name)}`, `${value}px`);
	for (const [name, value] of Object.entries(spacing)) add(`space-${kebab(name)}`, `${value}px`);
	// The size group already says "size": iconSize becomes --oito2-size-icon.
	for (const [name, value] of Object.entries(sizes)) {
		add(`size-${kebab(name.replace(/Size$/, ''))}`, `${value}px`);
	}
	for (const [name, value] of Object.entries(accentColors))
		add(`accent-${kebab(name)}`, value.toLowerCase());
	const families = [typography.fontFamily, ...typography.fontFamilyFallback, 'sans-serif'];
	add('font-family', families.map(family).join(', '));
	add('font-weight-emphasis', typography.emphasisWeight);
	for (const [name, style] of Object.entries(typography.scale)) {
		const prefix = `type-${kebab(name)}`;
		add(`${prefix}-size`, `${style.fontSize}px`);
		add(`${prefix}-line-height`, style.lineHeight);
		add(`${prefix}-weight`, style.fontWeight);
		add(`${prefix}-tracking`, `${style.letterSpacing}px`);
		add(
			prefix,
			`${style.fontWeight} ${style.fontSize}px / ${style.lineHeight} var(--oito2-font-family)`
		);
	}
	return file('packages/ui/src/lib/tokens/values.ts', [
		['\t:root {', ...lines, '\t}'].join('\n')
	]);
}

function schemesCss(): string {
	const rules: string[] = [];
	for (const brightness of ['light', 'dark'] as const) {
		for (const accent of Object.keys(values.accentColors)) {
			for (const highContrast of [false, true]) {
				const name = `${brightness}-${accent}${highContrast ? '-hc' : ''}`;
				const scheme = theme.createColorTheme({ brightness, accent, highContrast });
				rules.push(theme.colorThemeRule(scheme, `[data-oito2-scheme='${name}']`, '\t'));
			}
		}
	}
	return file('packages/ui/src/lib/theme', rules);
}

function presetsCss(): string {
	const rules: string[] = [];
	for (const preset of presets.themePresetNames) {
		for (const highContrast of [false, true]) {
			const name = `${kebab(preset)}${highContrast ? '-hc' : ''}`;
			const scheme = presets.presetColorTheme(preset, { highContrast });
			rules.push(theme.colorThemeRule(scheme, `[data-oito2-scheme='${name}']`, '\t'));
		}
	}
	return file('packages/ui-themes/src/lib/presets.ts', rules);
}

const outputs: [string, string][] = [
	['packages/ui/src/lib/styles/tokens.css', tokensCss()],
	['packages/ui/src/lib/styles/schemes.css', schemesCss()],
	['packages/ui-themes/src/lib/presets.css', presetsCss()]
];
await server.close();

const check = process.argv.includes('--check');
let stale = false;
for (const [path, css] of outputs) {
	if (check) {
		let current = '';
		try {
			current = readFileSync(`${root}${path}`, 'utf8');
		} catch {
			// A missing file counts as out of date.
		}
		if (current !== css) {
			console.error(`${path} is out of date: run \`pnpm generate\`.`);
			stale = true;
		}
	} else {
		writeFileSync(`${root}${path}`, css);
		console.log(`Wrote ${path}`);
	}
}
if (check) {
	if (stale) process.exit(1);
	console.log('Generated CSS is up to date.');
}
