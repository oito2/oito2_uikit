// Generates packages/ui/src/lib/styles/tokens.css from the token values in
// packages/ui/src/lib/tokens/values.ts. With --check it writes nothing and exits
// with status 1 when the file on disk differs from the generated one.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
	accentColors,
	radius,
	sizes,
	spacing,
	typography
} from '../../packages/ui/src/lib/tokens/values.ts';

const root = fileURLToPath(new URL('../../', import.meta.url));
const output = `${root}packages/ui/src/lib/styles/tokens.css`;
const header = readFileSync(`${root}tools/templates/header.css.txt`, 'utf8');

// Converts camelCase to kebab-case.
function kebab(name: string): string {
	return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

// Formats a family name for CSS, quoting names with spaces.
function family(name: string): string {
	return name.includes(' ') ? `'${name}'` : name;
}

function generate(): string {
	const lines: string[] = [];
	const add = (name: string, value: string | number) =>
		lines.push(`\t\t--oito2-${name}: ${value};`);
	for (const [name, value] of Object.entries(radius)) add(`radius-${kebab(name)}`, `${value}px`);
	for (const [name, value] of Object.entries(spacing)) add(`space-${kebab(name)}`, `${value}px`);
	// The size group already says "size": iconSize becomes --oito2-size-icon.
	for (const [name, value] of Object.entries(sizes)) {
		add(`size-${kebab(name.replace(/Size$/, ''))}`, `${value}px`);
	}
	for (const [name, value] of Object.entries(accentColors))
		add(`accent-${kebab(name)}`, value.toLowerCase());
	const families = [typography.fontFamily, ...typography.fontFamilyFallback, 'sans-serif'];
	add('font-family', families.map(family).join(', '));
	add('font-weight-emphasis', typography.emphasisWeight);
	for (const [name, style] of Object.entries(typography.scale)) {
		const prefix = `type-${kebab(name)}`;
		add(`${prefix}-size`, `${style.fontSize}px`);
		add(`${prefix}-line-height`, style.lineHeight);
		add(`${prefix}-weight`, style.fontWeight);
		add(`${prefix}-tracking`, `${style.letterSpacing}px`);
		add(
			prefix,
			`${style.fontWeight} ${style.fontSize}px / ${style.lineHeight} var(--oito2-font-family)`
		);
	}
	return [
		header.trimEnd(),
		'',
		'/* Generated by tools/generate-css from packages/ui/src/lib/tokens/values.ts. Do not edit. */',
		'',
		'@layer oito2 {',
		'\t:root {',
		...lines,
		'\t}',
		'}',
		''
	].join('\n');
}

const css = generate();
if (process.argv.includes('--check')) {
	let current = '';
	try {
		current = readFileSync(output, 'utf8');
	} catch {
		// A missing file counts as out of date.
	}
	if (current !== css) {
		console.error('tokens.css is out of date: run `pnpm generate`.');
		process.exit(1);
	}
	console.log('tokens.css is up to date.');
} else {
	writeFileSync(output, css);
	console.log(`Wrote ${output}`);
}
