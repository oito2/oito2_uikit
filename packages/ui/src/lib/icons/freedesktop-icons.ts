/** The suffixes a specification name may carry that don't change the icon. */
const ignoredSuffixes = ['-symbolic', '-rtl', '-ltr'];

/**
 * Returns the icon for a freedesktop.org Icon Naming Specification `name`, such as
 * `document-save`, or `null` when nothing matches.
 *
 * Trailing `-symbolic`, `-rtl` and `-ltr` suffixes are ignored, and a name without a
 * mapping falls back, as the specification does, to the name without its last
 * dash-separated part: `folder-documents` to `folder`.
 */
export function freedesktopIcon(name: string): IconComponent | null {
	let current = name;
	let trimmed = true;
	while (trimmed) {
		trimmed = false;
		for (const suffix of ignoredSuffixes) {
			if (current.endsWith(suffix)) {
				current = current.slice(0, -suffix.length);
				trimmed = true;
			}
		}
	}
	while (current !== '') {
		const icon = Object.hasOwn(freedesktopIcons, current)
			? freedesktopIcons[current]
			: undefined;
		if (icon) return icon;
		const dash = current.lastIndexOf('-');
		if (dash < 0) return null;
		current = current.slice(0, dash);
	}
	return null;
}
